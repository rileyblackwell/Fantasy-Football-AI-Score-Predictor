<script setup lang="ts">
import { onBeforeUnmount, onMounted, ref } from 'vue'
import { RouterLink, RouterView, useRoute } from 'vue-router'
import { scoring } from './lib/store'
import { SCORING_LABELS } from './lib/format'
import { loadSummary } from './lib/summary'
import type { Scoring } from './lib/api'

const formats = Object.entries(SCORING_LABELS) as [Scoring, string][]
const navLink =
  'whitespace-nowrap rounded-lg px-3 py-[7px] text-[14px] font-semibold text-muted no-underline transition-colors duration-150 hover:bg-surface-2 hover:text-fg'
const navActive = 'bg-surface-3! text-fg!'
const route = useRoute()

// Publish the top bar's height so sticky toolbars can sit right under it, even when it wraps on phones.
const header = ref<HTMLElement | null>(null)
let observer: ResizeObserver | null = null
onMounted(() => {
  if (!header.value || typeof ResizeObserver === 'undefined') return
  observer = new ResizeObserver(([entry]) => {
    const height = Math.round(entry.target.getBoundingClientRect().height)
    document.documentElement.style.setProperty('--header-h', `${height}px`)
  })
  observer.observe(header.value)
})
onBeforeUnmount(() => observer?.disconnect())

loadSummary()
</script>

<template>
  <header
    ref="header"
    class="sticky top-0 z-20 border-b border-line bg-surface/82 backdrop-blur-md backdrop-saturate-[160%]"
  >
    <div
      class="mx-auto flex min-h-[60px] max-w-[1160px] flex-wrap items-center gap-6 px-5 py-2.5 max-tab:justify-between max-tab:gap-x-4 max-tab:gap-y-2 max-tab:px-4 max-tab:pt-2.5 max-tab:pb-2"
    >
      <RouterLink
        to="/"
        class="flex items-center gap-2.5 text-fg no-underline"
        aria-label="Fantasy Football Score Predictor home"
      >
        <img src="/favicon.svg" alt="" class="size-[34px] shrink-0" />
        <span
          class="font-display text-[21px] leading-none font-extrabold tracking-[0.01em] uppercase max-tab:text-[18px]"
          >Fantasy Football <em class="text-accent not-italic">Score Predictor</em></span
        >
      </RouterLink>
      <nav
        class="flex flex-1 gap-0.5 max-tab:order-3 max-tab:-mx-1.5 max-tab:basis-full max-tab:overflow-x-auto max-tab:[scrollbar-width:none]"
        aria-label="Main"
      >
        <RouterLink to="/" :class="navLink" :exact-active-class="navActive">Projections</RouterLink>
        <RouterLink to="/start-sit" :class="navLink" :active-class="navActive">Start/Sit</RouterLink>
        <RouterLink to="/accuracy" :class="navLink" :active-class="navActive">Scorecard</RouterLink>
        <RouterLink to="/about" :class="navLink" :active-class="navActive">How it works</RouterLink>
      </nav>
      <!-- The scorecard and model pages only use PPR, so the scoring switch is hidden there. -->
      <div
        v-if="!route.meta.pprOnly"
        class="inline-flex rounded-control border border-line bg-surface-2 p-[3px]"
        role="radiogroup"
        aria-label="Scoring format"
      >
        <button
          v-for="[value, label] in formats"
          :key="value"
          type="button"
          role="radio"
          :aria-checked="scoring === value"
          class="rounded-[7px] px-3 py-[5px] text-[13px] font-bold transition-[color,background-color,box-shadow] duration-150"
          :class="
            scoring === value
              ? 'bg-accent text-on-accent shadow-[0_1px_3px_color-mix(in_srgb,var(--accent)_40%,transparent)]'
              : 'text-muted hover:text-fg'
          "
          @click="scoring = value"
        >
          {{ label }}
        </button>
      </div>
    </div>
  </header>
  <main class="mx-auto w-full max-w-[1160px] flex-1 px-5 pt-7 pb-14 max-tab:px-3.5 max-tab:pt-5 max-tab:pb-11">
    <RouterView />
  </main>
  <footer
    class="border-t border-line px-5 pt-6 pb-8 text-center text-[13px] leading-[1.6] text-balance text-muted"
  >
    Projections are generated by a machine-learning model trained on every NFL game since 2016. Data from
    <a href="https://github.com/nflverse" target="_blank" rel="noopener" class="font-semibold">nflverse</a>. For
    entertainment, not betting advice.
  </footer>
</template>
